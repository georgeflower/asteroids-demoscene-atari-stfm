def cell(rows):
    out = []
    for row in rows:
        value = 0
        for column, pixel in enumerate(row):
            if pixel == "#":
                value |= 0x80 >> (column + 1)   # one pixel of left padding
        out.append(value)
    out.append(0)   # eighth row stays empty
    return out


def main():
    path = sys.argv[1] if len(sys.argv) > 1 else "include/font_data.h"
    lines = ["/* Generated by tools/genfont.py - do not edit. */",
             "#ifndef FONT_DATA_H", "#define FONT_DATA_H", "",
             "/* 96 glyphs: ASCII 32..126 (upper case only) and, at index 95, a small ship icon (code 127). */",
             "static const unsigned char font_data[96][8] = {"]
    for code in list(range(32, 127)) + [127]:
        ch = chr(code)
        rows = GLYPHS.get(ch, BLANK)
        lines.append("    {" + ", ".join("0x%02x" % v for v in cell(rows)) + "},  /* %d %s */" %
                     (code, ch if 32 <= code < 127 else "ship"))
    lines += ["};", "", "#endif", ""]
    with open(path, "w", newline="\n") as f:
        f.write("\n".join(lines))


if __name__ == "__main__":
    main()
